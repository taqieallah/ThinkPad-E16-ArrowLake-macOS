#!/usr/bin/env python3
"""Generate kext/APVSites.generated.hpp from kext/sites.json.

sites.json is the single source of truth for the AppleParavirtGPU 25G241 BAR0
interception sites. It is consumed by:
  - tooling/verify-sites.py  (validates the bytes/spans against the real Mach-O)
  - tooling/stub-sim.cpp     (executes the generated stubs under Rosetta)
  - kext/SiteTable.hpp       (through this generated header)
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SITES = ROOT / "kext" / "sites.json"
OUT = ROOT / "kext" / "APVSites.generated.hpp"

DEST = {
    "none": 0xFF,
    "rax": 0, "rcx": 1, "rdx": 2, "rbx": 3, "rbp": 5,
    "rsi": 6, "rdi": 7, "r8": 8, "r9": 9, "r10": 10, "r11": 11,
    "r12": 12, "r14": 14,
}
KIND = {"read32": 0, "write_imm": 1, "version_pair": 2, "read_branch": 3}
SLOTS = {
    "rax": 0, "rcx": 8, "rdx": 16, "rsi": 24, "rdi": 32, "r8": 40, "r9": 48,
    "r10": 56, "r11": 64, "rbx": 72, "rbp": 80,
}


def cbytes(hex_string: str) -> str:
    raw = bytes.fromhex(hex_string) if hex_string else b""
    if len(raw) > 16:
        raise SystemExit("site byte string longer than 16 bytes")
    return ", ".join(f"0x{b:02x}" for b in raw) + ("," if raw else "")


def main() -> int:
    doc = json.loads(SITES.read_text())
    rows = []
    for site in doc["sites"]:
        original = bytes.fromhex(site["original"])
        span = int(site["span"])
        if span != len(original):
            raise SystemExit(f"site {site['name']}: span {span} != original length {len(original)}")
        if span < 5:
            raise SystemExit(f"site {site['name']}: span {span} cannot hold a near call")
        if site["kind"] == "read_branch":
            if int(site.get("branch_target", 0)) != int(site["text_offset"]) + span:
                raise SystemExit(f"site {site['name']}: branch_target is not text_offset + span")
        elif int(site["continuation"]) != int(site["text_offset"]) + span:
            raise SystemExit(f"site {site['name']}: continuation is not text_offset + span")
        reproduce = bytes.fromhex(site["reproduce"]) if site["reproduce"] else b""
        if len(reproduce) > 8:
            raise SystemExit(f"site {site['name']}: reproduce longer than 8 bytes")
        rows.append(
            "    {"
            f"{int(site['id'])}, 0x{int(site['text_offset']):x}, {span}, "
            "{" + cbytes(site["original"]) + "}, "
            f"0x{int(site['continuation']):x}, 0x{int(site.get('branch_target', 0)):x}, "
            f"0x{int(site['bar_offset']):x}, "
            f"{SLOTS[site['base_slot']] if isinstance(site['base_slot'], str) else int(site['base_slot'])}, "
            f"{site.get('value_slot', 255) if isinstance(site.get('value_slot', 255), int) else SLOTS[site['value_slot']]}, "
            f"{DEST[site['dest']]}, "
            f"0x{int(site.get('immediate', 0)):x}, "
            "{" + cbytes(site["reproduce"]) + "}, "
            f"{len(reproduce)}, {KIND[site['kind']]}, \"{site['name']}\""
            "},"
        )
    body = "\n".join(rows)
    header = f"""// Generated by tooling/gen-site-table.py from kext/sites.json. Do not edit.
// Included from inside namespace e16 in SiteTable.hpp.
constexpr size_t kSiteTableCount = {len(rows)};
constexpr SiteSpec kSiteTable[] = {{
{body}
}};
"""
    OUT.write_text(header)
    print(f"wrote {OUT} ({len(rows)} sites)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
